// Generates the assets for being out of water:
//  - Arrakis_Thirst_Slow_05 .. _95: entity effects that set the movement speed (HorizontalSpeedMultiplier, the field the
//    vanilla Slow effect uses) in 5% steps. WaterSystem picks the step nearest to ZeroWaterSpeedMultiplier, so the speed
//    is a config value although assets cannot be.
//  - Arrakis_Thirst: the damage cause for the thirst damage (no armour or resistance reduction, no durability loss).
//   node tools/assets/make_thirst.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..', 'src', 'main', 'resources', 'Server', 'Entity');
const effects = path.join(root, 'Effects', 'Water_of_Arrakis');
const damage = path.join(root, 'Damage');
fs.mkdirSync(effects, { recursive: true });
fs.mkdirSync(damage, { recursive: true });

for (let pct = 5; pct <= 95; pct += 5) {
    const name = `Arrakis_Thirst_Slow_${String(pct).padStart(2, '0')}.json`;
    fs.writeFileSync(path.join(effects, name), JSON.stringify({
        $Comment: `Movement speed x${pct / 100} while water is 0 (generated by tools/assets/make_thirst.js). Renewed by WaterSystem and removed the moment water is above 0.`,
        Duration: 2,
        ApplicationEffects: { HorizontalSpeedMultiplier: pct / 100 }
    }, null, 2));
}
fs.writeFileSync(path.join(damage, 'Arrakis_Thirst.json'), JSON.stringify({
    DurabilityLoss: false,
    StaminaLoss: false,
    BypassResistances: true
}, null, 2));
console.log('wrote 19 slow effects and the Arrakis_Thirst damage cause');
